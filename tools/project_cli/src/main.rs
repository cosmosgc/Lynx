use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use backend_nakama::{NakamaClient, NakamaConfig};
use clap::{Args, Parser, Subcommand, ValueEnum};
use engine_content::{ContentLoader, sha256_hex};
use engine_core::schema::ComponentRegistry;
use game_api::HealthService;
use serde_json::{Value, json};

#[derive(Parser)]
#[command(name = "lynx")]
#[command(version)]
#[command(about = "Lynx project scaffolding, diagnostics, and validation")]
struct Cli {
    #[arg(long, global = true)]
    json: bool,

    #[command(subcommand)]
    command: Commands,
}

#[derive(Subcommand)]
enum Commands {
    New(NewArgs),
    Doctor(DoctorArgs),
    Validate(ValidateArgs),
    Content(ContentArgs),
}

#[derive(Args)]
struct NewArgs {
    name: String,

    #[arg(long, default_value = "minimal")]
    template: Template,

    #[arg(long, default_value = ".")]
    output: PathBuf,
}

#[derive(Args)]
struct DoctorArgs {
    #[arg(long)]
    project: Option<PathBuf>,

    #[arg(long)]
    backend: bool,
}

#[derive(Args)]
struct ValidateArgs {
    #[arg(long)]
    project: PathBuf,
}

#[derive(Args)]
struct ContentArgs {
    #[command(subcommand)]
    command: ContentCommand,
}

#[derive(Subcommand)]
enum ContentCommand {
    Hash(HashArgs),
}

#[derive(Args)]
struct HashArgs {
    path: PathBuf,
}

#[derive(Clone, Copy, Debug, ValueEnum)]
enum Template {
    Minimal,
    Mmorpg,
}

impl Template {
    fn as_str(self) -> &'static str {
        match self {
            Self::Minimal => "minimal",
            Self::Mmorpg => "mmorpg",
        }
    }
}

fn main() {
    if let Err(error) = run() {
        let message = error.to_string();
        eprintln!("{message}");
        std::process::exit(1);
    }
}

fn run() -> Result<()> {
    let cli = Cli::parse();

    let output = match cli.command {
        Commands::New(args) => new_project(args)?,
        Commands::Doctor(args) => doctor(args)?,
        Commands::Validate(args) => validate_project(args)?,
        Commands::Content(args) => content(args)?,
    };

    if cli.json {
        println!("{}", serde_json::to_string_pretty(&output)?);
    } else {
        println!("{}", render_human_output(&output));
    }

    Ok(())
}

fn new_project(args: NewArgs) -> Result<Value> {
    let output_dir = absolute_path(args.output.as_path())?;
    let project_name = sanitize_name(&args.name)?;

    if output_dir.exists() && !output_dir.is_dir() {
        bail!("output path exists and is not a directory: {}", output_dir.display());
    }

    let created_files = vec![
        create_file(
            output_dir.join("Cargo.toml"),
            cargo_toml_for(&project_name, repo_root(), &args.template)?
                .as_bytes(),
        )?,
        create_file(
            output_dir.join("README.md"),
            format!(
                "# {project_name}\n\nThis project was generated by the Lynx project CLI.\n"
            )
            .as_bytes(),
        )?,
        create_file(
            output_dir.join("src/main.rs"),
            project_main(&project_name).as_bytes(),
        )?,
        create_directory(output_dir.join("localization"))?,
        create_file(
            output_dir.join("localization/pt-BR.ron"),
            pt_br_catalog().as_bytes(),
        )?,
        create_directory(output_dir.join("entities"))?,
        create_file(
            output_dir.join("entities/README.md"),
            b"Add authored definitions here.\n",
        )?,
        create_directory(output_dir.join("content/localization"))?,
        create_file(
            output_dir.join("content/localization/pt-BR.ron"),
            pt_br_catalog().as_bytes(),
        )?,
        create_directory(output_dir.join("content/definitions"))?,
        create_file(
            output_dir.join("content/definitions/README.md"),
            b"Add authored definitions here.\n",
        )?,
        create_file(
            output_dir.join(".env.example"),
            b"LYNX_PG_HOST=127.0.0.1\nLYNX_PG_PORT=5432\nLYNX_PG_DATABASE=lynx\nLYNX_PG_USER=lynx\nLYNX_PG_PASSWORD=change-me\n",
        )?,
    ];

    Ok(json!({
        "ok": true,
        "command": "new",
        "name": project_name,
        "template": args.template.as_str(),
        "path": output_dir.to_string_lossy(),
        "files": created_files,
    }))
}

fn doctor(args: DoctorArgs) -> Result<Value> {
    let mut report = json!({
        "ok": true,
        "command": "doctor",
        "project": null,
        "backend": null,
    });

    let has_project = args.project.is_some();
    if let Some(project_path) = args.project.as_ref() {
        let dir = absolute_path(project_path.as_path())?;
        let project_status = validate_dir(dir.as_path())?;
        report["project"] = project_status;
        report["ok"] = Value::Bool(
            report["ok"].as_bool().unwrap() && report["project"]["ok"].as_bool().unwrap(),
        );
    }

    if args.backend {
        let backend_status = check_backend()?;
        report["backend"] = backend_status;
        report["ok"] = Value::Bool(
            report["ok"].as_bool().unwrap() && report["backend"]["ok"].as_bool().unwrap(),
        );
    }

    if !has_project && !args.backend {
        let dir = absolute_path(Path::new("."))?;
        let project_status = validate_dir(dir.as_path())?;
        report["project"] = project_status;
        report["ok"] = Value::Bool(
            report["ok"].as_bool().unwrap() && report["project"]["ok"].as_bool().unwrap(),
        );
    }

    Ok(report)
}

fn validate_project(args: ValidateArgs) -> Result<Value> {
    let project_dir = absolute_path(args.project.as_path())?;
    let status = validate_dir(project_dir.as_path())?;
    Ok(status)
}

fn content(args: ContentArgs) -> Result<Value> {
    match args.command {
        ContentCommand::Hash(hash_args) => hash_file(hash_args.path),
    }
}

fn hash_file(path: PathBuf) -> Result<Value> {
    let path = absolute_path(path.as_path())?;
    let bytes = fs::read(&path)
        .with_context(|| format!("failed to read {}", path.display()))?;
    let digest = sha256_hex(&bytes);
    Ok(json!({
        "ok": true,
        "command": "content hash",
        "path": path.to_string_lossy(),
        "sha256": digest,
    }))
}

fn validate_dir(project_dir: &Path) -> Result<Value> {
    if !project_dir.exists() {
        return Ok(json!({
            "ok": false,
            "path": project_dir.to_string_lossy(),
            "errors": [format!("project missing: {}", project_dir.display())],
            "warnings": [],
            "definitions": 0,
            "catalogs": 0,
        }));
    }

    if !project_dir.is_dir() {
        return Ok(json!({
            "ok": false,
            "path": project_dir.to_string_lossy(),
            "errors": [format!("project path is not a directory: {}", project_dir.display())],
            "warnings": [],
            "definitions": 0,
            "catalogs": 0,
        }));
    }

    let registry = ComponentRegistry::new();
    let loader = ContentLoader::new(registry);
    let (set, report) = loader.load_project(project_dir);

    let errors: Vec<String> = report.errors().map(|item| item.to_string()).collect();
    let warnings: Vec<String> = report.warnings().map(|item| item.to_string()).collect();

    let ok = errors.is_empty();

    Ok(json!({
        "ok": ok,
        "path": project_dir.to_string_lossy(),
        "errors": errors,
        "warnings": warnings,
        "definitions": set.definitions.len(),
        "catalogs": set.catalogs.len(),
    }))
}

fn check_backend() -> Result<Value> {
    let url = backend_url();
    let client = NakamaClient::new(NakamaConfig::new(url.clone()));

    match client {
        Ok(client) => match client.health() {
            Ok(_) => Ok(json!({
                "ok": true,
                "url": url,
                "healthy": true,
                "message": "Nakama health check passed",
            })),
            Err(error) => Ok(json!({
                "ok": false,
                "url": url,
                "healthy": false,
                "message": error.to_string(),
            })),
        },
        Err(error) => Ok(json!({
            "ok": false,
            "url": url,
            "healthy": false,
            "message": error.to_string(),
        })),
    }
}

fn backend_url() -> String {
    std::env::var("LYNX_NAKAMA_URL")
        .or_else(|_| std::env::var("NAKAMA_URL"))
        .or_else(|_| std::env::var("NAKAMA_BASE_URL"))
        .unwrap_or_else(|_| "http://127.0.0.1:7350".to_string())
}

fn render_human_output(output: &Value) -> String {
    if output["command"] == "new" {
        let ok = output["ok"].as_bool().unwrap_or(false);
        let path = output["path"].as_str().unwrap_or(".");
        let template = output["template"].as_str().unwrap_or("unknown");
        let name = output["name"].as_str().unwrap_or("unknown");
        let empty_files = Vec::new();
        let files = output["files"].as_array().unwrap_or(&empty_files);
        if ok {
            let mut lines = vec![format!("Created project '{name}' from template '{template}' at {path}")];
            for file in files {
                lines.push(format!("- {}", file.as_str().unwrap_or("")));
            }
            return lines.join("\n");
        }
        return format!("Project creation failed: {}", output["message"].as_str().unwrap_or("unknown error"));
    }

    if output["command"] == "content hash" {
        let sha = output["sha256"].as_str().unwrap_or("unknown");
        return format!("SHA-256: {sha}");
    }

    if output["command"] == "doctor" {
        let ok = output["ok"].as_bool().unwrap_or(false);
        let backend = output["backend"].as_object();
        let project = output["project"].as_object();
        let mut lines = vec![format!("Doctor status: {}", if ok { "ok" } else { "issues found" })];
        if let Some(backend) = backend {
            lines.push(format!("- backend: {} ({})", backend["healthy"], backend["message"].as_str().unwrap_or("")));
        }
        if let Some(project) = project {
            lines.push(format!("- project: {} ({} errors, {} warnings)",
                project["ok"],
                project["errors"].as_array().map_or(0, |items| items.len()),
                project["warnings"].as_array().map_or(0, |items| items.len())
            ));
        }
        return lines.join("\n");
    }

    if output["ok"].as_bool().unwrap_or(false) {
        let path = output["path"].as_str().unwrap_or(".");
        return format!("Validation passed for {}", path);
    }

    let errors = output["errors"].as_array().map_or(0, |items| items.len());
    format!("Validation failed with {} error(s)", errors)
}

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .unwrap_or_else(|| Path::new("."))
        .to_path_buf()
}

fn absolute_path(path: &Path) -> Result<PathBuf> {
    if path.is_absolute() {
        return Ok(path.to_path_buf());
    }
    Ok(std::env::current_dir()?.join(path))
}

fn sanitize_name(value: &str) -> Result<String> {
    let trimmed = value.trim();
    if trimmed.is_empty() {
        bail!("project name must not be empty");
    }
    let cleaned: String = trimmed
        .chars()
        .filter(|ch| ch.is_ascii_alphanumeric() || matches!(ch, '-' | '_'))
        .collect();
    if cleaned.is_empty() {
        bail!("project name must contain at least one letter or digit");
    }
    Ok(cleaned)
}

fn create_directory(path: PathBuf) -> Result<String> {
    if !path.exists() {
        fs::create_dir_all(&path)
            .with_context(|| format!("failed to create directory {}", path.display()))?;
    }
    Ok(path.to_string_lossy().replace('\\', "/").to_string())
}

fn create_file(path: PathBuf, contents: &[u8]) -> Result<String> {
    if let Some(parent) = path.parent() {
        if !parent.exists() {
            fs::create_dir_all(parent)
                .with_context(|| format!("failed to create directory {}", parent.display()))?;
        }
    }
    fs::write(&path, contents)
        .with_context(|| format!("failed to write {}", path.display()))?;
    Ok(path.to_string_lossy().replace('\\', "/").to_string())
}

fn project_main(project_name: &str) -> String {
    format!(
        "fn main() {{\n    println!(\"Welcome to {project_name}!\");\n}}\n"
    )
}

fn cargo_toml_for(project_name: &str, repo_root: PathBuf, _template: &Template) -> Result<String> {
    let repo_root = repo_root.to_string_lossy().replace('\\', "\\\\");

    Ok(format!(
        "[package]\nname = \"{project_name}\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n[dependencies]\nengine_core = {{ path = \"{repo_root}\\\\crates\\\\engine_core\" }}\nengine_content = {{ path = \"{repo_root}\\\\crates\\\\engine_content\" }}\nengine_sim = {{ path = \"{repo_root}\\\\crates\\\\engine_sim\" }}\nbackend_nakama = {{ path = \"{repo_root}\\\\crates\\\\backend_nakama\" }}\nserde = {{ version = \"1\", features = [\"derive\"] }}\nserde_json = \"1\"\nron = \"0.12\"\n\n[profile.dev]\ndebug = 1\n\n[profile.release]\nlto = \"thin\"\ncodegen-units = 1\n",
        repo_root = repo_root,
        project_name = project_name,
    ))
}

fn pt_br_catalog() -> &'static str {
    "(\n    locale: \"pt-BR\",\n    messages: {\n        \"game.title\": \"Bem-vindo ao Lynx\",\n        \"ui.label.inventory\": \"Inventário\",\n    },\n)\n"
}
